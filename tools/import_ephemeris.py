"""Import pinned PyEphem numeric tables and assignment-only lunar expressions."""

import argparse
import pathlib
import re
import subprocess


REFERENCE = '6be1e55540fd32aaeff272733190128155e8a35c'


def clean(source):
    return re.sub(r'/\*.*?\*/', '', source, flags=re.DOTALL)


def array(source, name):
    match = re.search(r'\b%s\s*(?:\[[^]]*\])+\s*=\s*\{' % name, source)
    start = match.end()
    end = source.index('};', start)
    return clean(source[start:end])


def number(value, floating):
    value = value.strip()
    if value.startswith('.'):
        value = '0' + value
    elif value.startswith('-.'):
        value = '-0' + value[1:]
    if floating and not any(char in value.lower() for char in '.e'):
        value += '.0'
    return value


def emit_array(source, name, target, rust_type, width=None):
    contents = array(source, name)
    values = [value.strip() for value in re.sub(r'[{}]', '', contents).split(',') if value.strip()]
    values = [number(value, rust_type == 'f64') for value in values]
    if width:
        while len(values) % width:
            values.append('0.0' if rust_type == 'f64' else '0')
        rows = ['[' + ','.join(values[i:i + width]) + ']' for i in range(0, len(values), width)]
        return 'pub static %s: [[%s;%s];%s] = [\n%s\n];\n' % (target, rust_type, width, len(rows), ',\n'.join(rows))
    return 'pub static %s: [%s;%s] = [\n%s\n];\n' % (target, rust_type, len(values), ','.join(values))


def floating_expressions(text):
    token = r'(?<![\w.])(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?(?![\w.])'
    text = re.sub(token, lambda match: number(match[0], True), text)
    return re.sub(r'\[(\d+)\.0\]', r'[\1]', text)


def moon_expressions(source):
    body = source.split('/* Mercury */', 1)[1].split('/* Prepare lookup table', 1)[0]
    body = body[:body.rfind('}')]
    body = re.sub(r'#if 0.*?#endif', '', body, flags=re.DOTALL)
    body = re.sub(r'/\* Precession of the equinox.*?/\* Free librations\.\s*\*/', '', body, flags=re.DOTALL)
    body = clean(body).replace('Args', 'args').replace('mods3600', 'mod_arcsec')
    body = re.sub(r'\b(?:Ea_arcsec|NF_arcsec|pA_precession)\s*=\s*x\s*;', '', body)
    body = body.replace('LP_equinox = x;', 'let lp = x;')
    body = re.sub(r'\bT2\b', 't2', body)
    body = re.sub(r'\bT\b', 't', body)
    body = floating_expressions(body)
    return ('pub fn mean_elements(jed: f64) -> ([f64;18],f64) {\n'
            'let t = (jed-2451545.0)/36525.0; let t2 = t*t;\n'
            'let mut args = [0.0;18]; let mut x: f64;\n' + body + '\n(args,lp)\n}\n')


def moon_fast(source):
    body = source.split('moon_fast (double mj, double *lam, double *bet, double *hp, double *msp,\ndouble *mdp)', 1)[1]
    body = body[body.index('{') + 1:body.index('\n}\n')]
    body = clean(body)
    declarations = re.findall(r'double\s+([^;]+);', body)
    names = [name.strip() for declaration in declarations for name in declaration.split(',')]
    body = re.sub(r'double\s+[^;]+;', '', body)
    body = re.sub(r'\(long\)(m[1-6])', r'\1.trunc()', body)
    for name in ['lam', 'bet', 'hp', 'msp', 'mdp']:
        body = body.replace('*' + name, name)
    body = body.replace('range (lam, 2*PI);', 'lam = range(lam,2.0*PI);')
    body = floating_expressions(body)
    return ('pub fn moon_fast(mj: f64) -> [f64;5] {\n' +
            '\n'.join('let mut %s: f64;' % name for name in names + ['lam', 'bet', 'hp', 'msp', 'mdp']) +
            '\n' + body + '\n[lam,bet,hp,msp,mdp]\n}\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=pathlib.Path)
    options = parser.parse_args()
    assert subprocess.check_output(['git', '-C', str(options.source), 'rev-parse', 'HEAD'], text=True).strip() == REFERENCE
    root = options.source / 'libastro'
    result = ['//! Generated by tools/import_ephemeris.py from PyEphem ' + REFERENCE + '.\n'
              '//! Copyright Elwood Downey, Brandon Rhodes and S. L. Moshier. See vendor/LICENSE.ephem.\n']
    for filename, arrays in [
            ('vsop87_data.c', [('vx_earth', 'EARTH', 'f64', 3), ('vn_earth', 'EARTH_INDEX', 'usize', 3)]),
            ('nutation.c', [('delaunay', 'DELAUNAY', 'f64', 4), ('multarg', 'NUT_ARGUMENTS', 'i32', 5),
                            ('ampsecul', 'NUT_SECULAR', 'f64', 5), ('ampconst', 'NUT_CONSTANT', 'f64', 2)]),
            ('deltat.c', [('dt', 'DELTA_TABLE', 'i32', None), ('m_s', 'DELTA_HISTORICAL', 'i32', None)]),
            ('moon.c', [('lrtabl', 'LUNAR_LONGITUDE', 'f64', None), ('lrtabr', 'LUNAR_RADIUS', 'f64', None),
                        ('lrargs', 'LUNAR_ARGUMENTS', 'i32', None), ('btabl', 'LUNAR_LATITUDE', 'f64', None),
                        ('bargs', 'LATITUDE_ARGUMENTS', 'i32', None)])]:
        source = (root / filename).read_text()
        for name, target, kind, width in arrays:
            result.append(emit_array(source, name, target, kind, width))
    destination = pathlib.Path(__file__).resolve().parents[1] / 'src/astro'
    destination.mkdir(exist_ok=True)
    (destination / 'data.rs').write_text('\n'.join(result[:1]) + '#![allow(clippy::excessive_precision,clippy::approx_constant)]\n' + '\n'.join(result[1:]))
    moon = (root / 'moon.c').read_text()
    (destination / 'lunar_expressions.rs').write_text(result[0] +
        '#![allow(unused_mut,unused_assignments,clippy::assign_op_pattern,clippy::excessive_precision)]\n' +
        'use super::{range,mod_arcsec};\nuse std::f64::consts::PI;\n'
        'fn sin(v:f64)->f64{v.sin()}\nfn cos(v:f64)->f64{v.cos()}\nfn degrad(v:f64)->f64{v*PI/180.0}\n' +
        moon_expressions(moon) + moon_fast(moon))


if __name__ == '__main__':
    main()
